CREATE TABLE IF NOT EXISTS public.notification_push_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id INTEGER NOT NULL UNIQUE
        REFERENCES public.notifications(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'PROCESSING', 'SENT', 'NO_DEVICE')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    available_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    locked_until TIMESTAMPTZ,
    claim_token UUID,
    created_at TIMESTAMPTZ NOT NULL DEFAULT statement_timestamp(),
    sent_at TIMESTAMPTZ,
    last_error TEXT,
    CHECK (
        (status = 'PROCESSING' AND locked_until IS NOT NULL AND claim_token IS NOT NULL)
        OR (status <> 'PROCESSING' AND locked_until IS NULL AND claim_token IS NULL)
    ),
    CHECK (
        (status IN ('SENT', 'NO_DEVICE') AND sent_at IS NOT NULL)
        OR (status IN ('PENDING', 'PROCESSING') AND sent_at IS NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_notification_push_outbox_pending
    ON public.notification_push_outbox (available_at, id)
    WHERE status = 'PENDING';

CREATE INDEX IF NOT EXISTS idx_notification_push_outbox_expired_claims
    ON public.notification_push_outbox (locked_until, id)
    WHERE status = 'PROCESSING';
